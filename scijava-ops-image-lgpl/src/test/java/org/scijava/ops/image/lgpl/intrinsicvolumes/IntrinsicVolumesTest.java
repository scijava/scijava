	@Test
	public void testDisc() {
		final var r = 30.0;
		final var disc = binary(71, 71, 1, p -> sq(p[0] - 35) + sq(p[1] - 35) <=
			r * r);
		assertEquals(Math.PI * r * r, area(disc, null), 0.01 * Math.PI * r * r);
		assertEquals(2 * Math.PI * r, perimeter(disc, null, 4), 0.01 * 2 *
			Math.PI * r);
		assertEquals(2 * Math.PI * r, perimeter(disc, null, null), 0.01 * 2 *
			Math.PI * r);
		assertEquals(1, euler(disc, 4), EPS);
		assertEquals(1, euler(disc, 8), EPS);

		// An ellipse sampled with anisotropic spacing.
		final var ellipse = binary(71, 36, 1, p -> sq(p[0] - 35) + sq(2 * (p[1] -
			17.5)) <= r * r);
		final double[] s = { 1, 2 };
		assertEquals(Math.PI * r * r, area(ellipse, s), 0.02 * Math.PI * r * r);
		assertEquals(2 * Math.PI * r, perimeter(ellipse, s, 4), 0.02 * 2 *
			Math.PI * r);
	}

	@Test
	public void testEuler2D() {
		// An annulus has one hole.
		final var annulus = binary(41, 41, 1, p -> {
			final var d2 = sq(p[0] - 20) + sq(p[1] - 20);
			return d2 <= 18 * 18 && d2 > 10 * 10;
		});
		assertEquals(0, euler(annulus, 4), EPS);
		assertEquals(0, euler(annulus, 8), EPS);

		// Two diagonally adjacent pixels: two components (C4) or one (C8).
		final var diag = binary(4, 4, 1, p -> p[0] == p[1] && p[0] < 2);
		assertEquals(2, euler(diag, 4), EPS);
		assertEquals(1, euler(diag, 8), EPS);

		// A diamond outline encloses a hole only in 8-connectivity: in
		// 4-connectivity, its four pixels are separate and the hole merges with
		// the background.
		final var diamond = binary(5, 5, 1, p -> Math.abs(p[0] - 2) + Math.abs(
			p[1] - 2) == 1);
		assertEquals(4, euler(diamond, 4), EPS);
		assertEquals(0, euler(diamond, 8), EPS);

		// Objects touching the border are measured as if the image were padded.
		final var full = binary(5, 5, 1, p -> true);
		assertEquals(1, euler(full, 4), EPS);
		assertEquals(25, area(full, null), EPS);
	}

	@Test
	public void testBall() {
		final var r = 12.0;
		final var ball = binary(29, 29, 29, p -> sq(p[0] - 14) + sq(p[1] - 14) +
			sq(p[2] - 14) <= r * r);
		final var v = 4.0 / 3 * Math.PI * r * r * r;
		final var a = 4 * Math.PI * r * r;
		assertEquals(v, volume(ball, null), 0.02 * v);
		assertEquals(a, surface(ball, null, 13), 0.02 * a);
		assertEquals(a, surface(ball, null, null), 0.02 * a);
		assertEquals(2 * r, meanBreadth(ball, null, 13, 8), 0.03 * 2 * r);
		assertEquals(2 * r, meanBreadth(ball, null, null, null), 0.03 * 2 * r);
		assertEquals(1, euler(ball, 6), EPS);
		assertEquals(1, euler(ball, 26), EPS);

		// A ball sampled with anisotropic spacing.
		final var ellipsoid = binary(29, 29, 15, p -> sq(p[0] - 14) + sq(p[1] -
			14) + sq(2 * (p[2] - 7)) <= r * r);
		final double[] s = { 1, 1, 2 };
		assertEquals(v, volume(ellipsoid, s), 0.02 * v);
		assertEquals(a, surface(ellipsoid, s, 13), 0.03 * a);
		assertEquals(2 * r, meanBreadth(ellipsoid, s, 13, 8), 0.04 * 2 * r);
	}

	@Test
	public void testEuler3D() {
		// A hollow ball (spherical shell) has one cavity.
		final var shell = binary(25, 25, 25, p -> {
			final var d2 = sq(p[0] - 12) + sq(p[1] - 12) + sq(p[2] - 12);
			return d2 <= 11 * 11 && d2 > 6 * 6;
		});
		assertEquals(2, euler(shell, 6), EPS);
		assertEquals(2, euler(shell, 26), EPS);

		// A solid torus has one tunnel.
		final double big = 10, small = 4;
		final var torus = binary(31, 31, 13, p -> {
			final var rho = Math.sqrt(sq(p[0] - 15) + sq(p[1] - 15)) - big;
			return sq(rho) + sq(p[2] - 6) <= small * small;
		});
		assertEquals(0, euler(torus, 6), EPS);
		assertEquals(0, euler(torus, 26), EPS);

		// A cube has Euler number 1, and so does a cube touching the border.
		final var cube = binary(6, 6, 6, p -> p[0] < 4 && p[1] < 4 && p[2] < 4);
		assertEquals(1, euler(cube, 6), EPS);
		assertEquals(1, euler(cube, 26), EPS);
		assertEquals(64, volume(cube, null), EPS);

		// Two voxels sharing only a vertex: two components (C6) or one (C26).
		final var pair = binary(3, 3, 3, p -> p[0] == p[1] && p[1] == p[2] &&
			p[0] < 2);
		assertEquals(2, euler(pair, 6), EPS);
		assertEquals(1, euler(pair, 26), EPS);
	}

	@Test
	public void testEulerCharacteristic26N() {
		// topology.eulerCharacteristic26N ignores the configurations crossing
		// the border, so it matches on an image padded with background.
		final var img = binary(9, 8, 7, p -> hash(p[0], p[1], p[2]) % 100 < 40);
		final var padded = binary(11, 10, 9, p -> p[0] > 0 && p[1] > 0 &&
			p[2] > 0 && p[0] < 10 && p[1] < 9 && p[2] < 8 && hash(p[0] - 1, p[1] -
				1, p[2] - 1) % 100 < 40);
		final var expected = new DoubleType();
		ops.op("topology.eulerCharacteristic26N").input(padded).output(expected)
			.compute();
		assertEquals(expected.get(), euler(img, 26), EPS);
	}

