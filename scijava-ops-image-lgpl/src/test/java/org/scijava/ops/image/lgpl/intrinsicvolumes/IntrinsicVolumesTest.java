	// -- Helper methods --

	private static double area(final RandomAccessibleInterval<BitType> img,
		final double[] spacing)
	{
		return call("area", img, spacing);
	}

	private static double perimeter(final RandomAccessibleInterval<BitType> img,
		final double[] spacing, final Integer dirs)
	{
		return call("perimeter", img, spacing, dirs);
	}

	private static double volume(final RandomAccessibleInterval<BitType> img,
		final double[] spacing)
	{
		return call("volume", img, spacing);
	}

	private static double surface(final RandomAccessibleInterval<BitType> img,
		final double[] spacing, final Integer dirs)
	{
		return call("surfaceArea", img, spacing, dirs);
	}

	private static double meanBreadth(
		final RandomAccessibleInterval<BitType> img, final double[] spacing,
		final Integer dirs, final Integer conn2d)
	{
		return call("meanBreadth", img, spacing, dirs, conn2d);
	}

	private static double euler(final RandomAccessibleInterval<BitType> img,
		final Integer conn)
	{
		return call("eulerNumber", img, conn);
	}

	private static Map<String, Double> densities(
		final RandomAccessibleInterval<BitType> img, final double[] spacing,
		final Integer dirs, final Integer conn)
	{
		return run("densities", DENSITIES, inputs(img, spacing, dirs, conn));
	}

	private static double interfaceArea(final ImgLabeling<Integer, IntType> lab,
		final int l1, final int l2, final double[] spacing, final Integer dirs)
	{
		final var in = inputs(lab, spacing, dirs);
		final var inputs = new Object[in.length + 2];
		inputs[0] = lab;
		inputs[1] = l1;
		inputs[2] = l2;
		System.arraycopy(in, 1, inputs, 3, in.length - 1);
		return run("interfaceArea", Nil.of(Double.class), inputs);
	}

	private static Map<Integer, Double> perLabel(final String name,
		final ImgLabeling<Integer, IntType> lab, final Object... args)
	{
		return run(name, PER_LABEL, inputs(lab, args));
	}

	private static double call(final String name,
		final RandomAccessibleInterval<BitType> img, final Object... args)
	{
		return run(name, Nil.of(Double.class), inputs(img, args));
	}

	private static <T> T run(final String name, final Nil<T> outType,
		final Object... in)
	{
		final var op = ops.op("features.intrinsicVolumes." + name);
		switch (in.length) {
			case 1:
				return op.input(in[0]).outType(outType).apply();
			case 2:
				return op.input(in[0], in[1]).outType(outType).apply();
			case 3:
				return op.input(in[0], in[1], in[2]).outType(outType).apply();
			case 4:
				return op.input(in[0], in[1], in[2], in[3]).outType(outType).apply();
			case 5:
				return op.input(in[0], in[1], in[2], in[3], in[4]).outType(outType)
					.apply();
			default:
				throw new IllegalArgumentException("Too many inputs: " + in.length);
		}
	}

	/**
	 * Builds the op inputs, omitting trailing null arguments so that the op
	 * defaults apply, and replacing a null spacing followed by other arguments
	 * with unit spacing.
	 */
	private static Object[] inputs(final RandomAccessibleInterval<?> img,
		final Object... args)
	{
		var n = args.length;
		while (n > 0 && args[n - 1] == null)
			n--;
		final var inputs = new Object[n + 1];
		inputs[0] = img;
		for (var i = 0; i < n; i++) {
			if (args[i] != null) inputs[i + 1] = args[i];
			else {
				final var ones = new double[img.numDimensions()];
				Arrays.fill(ones, 1);
				inputs[i + 1] = ones;
			}
		}
		return inputs;
	}

	private static void assertMap(final Map<Integer, Double> actual,
		final double... expected)
	{
		assertEquals(expected.length, actual.size());
		for (var i = 0; i < expected.length; i++)
			assertEquals(expected[i], actual.get(i + 1), EPS, "label " + (i + 1));
	}

	/** Pseudo-random hash of a position, also used by the MorphoLibJ harness. */
	private static int hash(final long x, final long y, final long z) {
		var v = ((int) x * 73856093) ^ ((int) y * 19349663) ^ ((int) z * 83492791);
		v ^= v >>> 13;
		v *= 0x5bd1e995;
		v ^= v >>> 15;
		return v & 0x7fffffff;
	}

	private static double sq(final double v) {
		return v * v;
	}

	private static RandomAccessibleInterval<BitType> binary(final int w,
		final int h, final int d, final Predicate<long[]> fg)
	{
		final Img<BitType> img = d == 1 ? ArrayImgs.bits(w, h) : ArrayImgs.bits(w,
			h, d);
		final var c = img.localizingCursor();
		final var pos = new long[3];
		while (c.hasNext()) {
			c.fwd();
			c.localize(pos);
			if (d == 1) pos[2] = 0;
			c.get().set(fg.test(pos));
		}
		return img;
	}

	private static ImgLabeling<Integer, IntType> labeling(final int w,
		final int h, final int d,
		final ToIntFunction<long[]> label)
	{
		final Img<IntType> index = d == 1 ? ArrayImgs.ints(w, h) : ArrayImgs.ints(
			w, h, d);
		final var c = index.localizingCursor();
		final var pos = new long[3];
		var max = 0;
		while (c.hasNext()) {
			c.fwd();
			c.localize(pos);
			if (d == 1) pos[2] = 0;
			final var v = label.applyAsInt(pos);
			c.get().set(v);
			max = Math.max(max, v);
		}
		return ImgLabeling.fromImageAndLabels(index, IntStream.rangeClosed(1,
			max).boxed().collect(Collectors.toList()));
	}

